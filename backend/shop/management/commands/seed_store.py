def _luhn_complete(prefix15):
    digits = [int(d) for d in prefix15]
    total = 0
    for i, d in enumerate(reversed(digits)):
        if i % 2 == 0:
            d = d * 2 - 9 if d > 4 else d * 2
        total += d
    return prefix15 + str((10 - total % 10) % 10)


class Command(BaseCommand):
    help = 'Add the starting product (in black), FAQ, policy pages and a sample card (only what is missing).'

    def handle(self, *args, **options):
        StoreSettings.load()  # free post, Tipax paid on delivery, 4 to 6 working days (the model's defaults)
        product, created = Product.objects.get_or_create(slug=PRODUCT['slug'], defaults=PRODUCT)
        self.stdout.write(f'Product: {"added" if created else "kept"} {product.name}')
        if not product.colors.exists():
            for position, (name, swatch, photo) in enumerate(COLORS):
                product.colors.create(name=name, swatch=swatch, photo=photo, position=position)
            self.stdout.write(f'Color: added {len(COLORS)}')
        if not Faq.objects.exists():
            for i, (question, answer) in enumerate(FAQS):
                Faq.objects.create(question=question, answer=answer, position=i)
            self.stdout.write(f'FAQ: added {len(FAQS)}')
        for i, (slug, title, body) in enumerate(PAGES):
            _, created = Page.objects.get_or_create(slug=slug, defaults={'title': title, 'body': body, 'position': i})
            if created:
                self.stdout.write(f'Page: added {slug}')
        if not Card.objects.exists():
            Card.objects.create(bank='بانک نمونه', number=_luhn_complete('603799000000001'),
                                holder='[نام صاحب کارت]')
            self.stdout.write('Card: added a sample card; replace it in the panel')
